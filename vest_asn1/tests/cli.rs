use std::fs;
use std::path::PathBuf;
use std::process::Command;
use std::time::{SystemTime, UNIX_EPOCH};

fn compiler() -> Command {
    Command::new(env!("CARGO_BIN_EXE_vest_asn1"))
}

fn fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures")
        .join(name)
}

struct TempDir(PathBuf);

impl TempDir {
    fn new() -> Self {
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path =
            std::env::temp_dir().join(format!("vest-asn1-cli-{}-{stamp}", std::process::id()));
        fs::create_dir(&path).unwrap();
        Self(path)
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

#[test]
fn help_and_version_do_not_require_a_schema() {
    let help = compiler().arg("--help").output().unwrap();
    assert!(help.status.success());
    assert!(String::from_utf8(help.stdout)
        .unwrap()
        .contains("--der-definition"));
    let version = compiler().arg("--version").output().unwrap();
    assert!(version.status.success());
    assert_eq!(
        String::from_utf8(version.stdout).unwrap().trim(),
        concat!("vest_asn1 ", env!("CARGO_PKG_VERSION"))
    );
}

#[test]
fn rejects_bad_arguments_without_reading_a_file() {
    for args in [&["--unknown"][..], &["--rules", "cer"], &[], &["--output"]] {
        let output = compiler().args(args).output().unwrap();
        assert_eq!(output.status.code(), Some(2));
        let error = String::from_utf8(output.stderr).unwrap();
        assert!(!error.contains("No such file"), "{error}");
        assert!(error.contains("--help"), "{error}");
    }
}

#[test]
fn emits_der_to_stdout_and_accepts_long_option_equals() {
    let der = compiler().arg(fixture("fixture.asn1")).output().unwrap();
    assert!(
        der.status.success(),
        "{}",
        String::from_utf8_lossy(&der.stderr)
    );
    assert!(String::from_utf8(der.stdout)
        .unwrap()
        .contains("Generated formats parse and serialize DER."));
    let ber = compiler()
        .arg("--rules=ber")
        .arg(fixture("fixture_ber.asn1"))
        .output()
        .unwrap();
    assert!(
        ber.status.success(),
        "{}",
        String::from_utf8_lossy(&ber.stderr)
    );
    assert!(String::from_utf8(ber.stdout)
        .unwrap()
        .contains("Generated formats parse and serialize BER."));
}

#[test]
fn rejects_conflicting_overrides() {
    let output = compiler()
        .args(["--der-definition", "Shared", "--ber-definition", "Shared"])
        .arg(fixture("fixture_mixed.asn1"))
        .output()
        .unwrap();
    assert!(!output.status.success());
    assert!(String::from_utf8(output.stderr)
        .unwrap()
        .contains("both DER and BER"));
}

#[test]
fn writes_a_file_and_keeps_it_unchanged_on_schema_errors() {
    let dir = TempDir::new();
    let destination = dir.0.join("generated.rs");
    let output = compiler()
        .arg(fixture("fixture.asn1"))
        .arg("--output")
        .arg(&destination)
        .output()
        .unwrap();
    assert!(output.status.success());
    assert!(output.stdout.is_empty());
    let expected = fs::read_to_string(&destination).unwrap();
    assert!(expected.starts_with("// @generated by vest_asn1 v"));

    let invalid = dir.0.join("invalid.asn1");
    fs::write(&invalid, "Example DEFINITIONS ::= BEGIN Value ::= BOOLEAN").unwrap();
    let output = compiler()
        .arg(&invalid)
        .arg("-o")
        .arg(&destination)
        .output()
        .unwrap();
    assert!(!output.status.success());
    assert!(String::from_utf8(output.stderr)
        .unwrap()
        .contains("Expected END"));
    assert_eq!(fs::read_to_string(&destination).unwrap(), expected);
}

#[test]
fn end_of_options_allows_a_dash_prefixed_filename() {
    let dir = TempDir::new();
    fs::write(
        dir.0.join("-schema.asn1"),
        "Example DEFINITIONS ::= BEGIN Flag ::= BOOLEAN END",
    )
    .unwrap();
    let output = compiler()
        .current_dir(&dir.0)
        .args(["--", "-schema.asn1"])
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
}
